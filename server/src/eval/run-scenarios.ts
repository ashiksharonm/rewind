// `npm run eval` — run every scenario in scenarios.ts against the simulated
// agent (real MCP tools server, throwaway SQLite store), score each recorded
// run, and write eval/results/{scenarios.json,summary.md}.
// Output omits run ids, timestamps, and latencies so it is byte-for-byte
// reproducible; CI re-runs it and fails if the committed results drift.
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

process.env.REWIND_DATA_DIR ??= mkdtempSync(join(tmpdir(), 'rewind-eval-'));

const { store } = await import('../store.js');
const { createRun, forkRun } = await import('../engine.js');
const { connectMcp } = await import('../mcp/client.js');
const { simulatedDriver } = await import('../agent/simulated.js');
const { evaluateRun } = await import('./trajectory.js');
const { diffEvaluations } = await import('./compare.js');
const { SCENARIOS } = await import('./scenarios.js');
type Report = ReturnType<typeof evaluateRun>;

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const outDir = join(repoRoot, 'eval', 'results');
const writeFixtures = process.argv.includes('--fixtures');

function waitForRun(id: string): Promise<void> {
  return new Promise((resolve) => {
    const t = setInterval(() => {
      if (store.getRun(id)?.status !== 'running') {
        clearInterval(t);
        resolve();
      }
    }, 20);
  });
}

const stable = (r: Report) => ({ ...r, runId: undefined });
const pct = (n: number | null | undefined) => (n === null || n === undefined ? '—' : `${(n * 100).toFixed(0)}%`);

await connectMcp();
const results = [];
for (const sc of SCENARIOS) {
  const base = createRun(simulatedDriver, 'simulated', { name: sc.id, prompt: sc.prompt });
  await waitForRun(base.id);
  let evaluated = base.id;

  if (sc.fork) {
    const steps = store.getSteps(base.id);
    const at = sc.fork.at;
    const target =
      at === 'prompt'
        ? steps[0]
        : 'tool' in at
          ? steps.find((s) => s.type === 'tool_call' && s.toolName === at.tool)
          : steps.filter((s) => s.type === 'llm_call')[at.llmTurn];
    if (!target) throw new Error(`${sc.id}: fork target not found`);
    const fork = forkRun(simulatedDriver, 'simulated', base.id, target.index, sc.fork.edit);
    await waitForRun(fork.id);
    evaluated = fork.id;
  }

  const report = evaluateRun(store.getRun(evaluated)!, store.getSteps(evaluated), sc.spec);
  const parentReport = sc.fork ? evaluateRun(store.getRun(base.id)!, store.getSteps(base.id), sc.spec) : null;
  const diff = parentReport ? diffEvaluations(parentReport, report) : null;
  results.push({
    id: sc.id,
    description: sc.description,
    prompt: sc.prompt,
    fork: sc.fork ?? null,
    spec: sc.spec,
    expectPass: sc.expectPass,
    verdictAsExpected: report.pass === sc.expectPass,
    report: stable(report),
    parentReport: parentReport ? stable(parentReport) : null,
    forkVsParent: diff,
  });

  if (writeFixtures && sc.id === 'tokyo-baseline') {
    const fixtures = join(repoRoot, 'eval', 'fixtures');
    mkdirSync(fixtures, { recursive: true });
    writeFileSync(
      join(fixtures, 'tokyo-baseline.simulated.trace.json'),
      JSON.stringify({ run: store.getRun(base.id), steps: store.getSteps(base.id) }, null, 2) + '\n',
    );
  }
}

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'scenarios.json'), JSON.stringify({ agent: simulatedDriver.model, results }, null, 2) + '\n');

const asExpected = results.filter((r) => r.verdictAsExpected).length;
const md = [
  '# Trajectory eval — simulated agent',
  '',
  `Generated by \`npm run eval\` (agent: \`${simulatedDriver.model}\`, tools: real MCP stdio server).`,
  'The simulated agent is scripted and deterministic, so these numbers describe the',
  'evaluator on known behaviour — they are not a benchmark of an LLM.',
  '',
  `**Evaluator verdicts matching expectation: ${asExpected}/${results.length}**`,
  '',
  '| Scenario | Mode | Pass | Expected | Traj. match | Precision | Recall | F1 | Tool calls | Steps | Outcome checks |',
  '|---|---|---|---|---|---|---|---|---|---|---|',
  ...results.map((r) => {
    const t = r.report.trajectory!;
    const o = r.report.outcome;
    const oc = o.checked ? `${o.checks.filter((c) => c.passed).length}/${o.checks.length}` : '—';
    return `| \`${r.id}\` | ${t.mode} | ${r.report.pass ? 'PASS' : 'FAIL'} | ${r.expectPass ? 'PASS' : 'FAIL'} | ${t.matched ? 'yes' : 'no'} | ${pct(t.precision)} | ${pct(t.recall)} | ${pct(t.f1)} | ${r.report.efficiency.toolCalls} | ${r.report.efficiency.steps} | ${oc} |`;
  }),
  '',
  '## Fork vs parent (same spec)',
  '',
  '| Scenario | Pass flip | Improved | Regressed |',
  '|---|---|---|---|',
  ...results
    .filter((r) => r.forkVsParent)
    .map(
      (r) =>
        `| \`${r.id}\` | ${r.forkVsParent!.passFlip} | ${r.forkVsParent!.improved.join(', ') || '—'} | ${r.forkVsParent!.regressed.join(', ') || '—'} |`,
    ),
  '',
  '## Failures explained',
  '',
  ...results
    .filter((r) => !r.report.pass)
    .flatMap((r) => [
      `- \`${r.id}\` — ${r.description}`,
      ...(r.report.trajectory!.missing.length
        ? [`  - missing: ${r.report.trajectory!.missing.map((m) => `${m.tool}(${JSON.stringify(m.args ?? {})})`).join(', ')}`]
        : []),
      ...(r.report.trajectory!.unexpected.length
        ? [`  - unexpected: ${r.report.trajectory!.unexpected.map((m) => `${m.tool}(${JSON.stringify(m.args)})`).join(', ')}`]
        : []),
      ...r.report.outcome.checks.filter((c) => !c.passed).map((c) => `  - outcome ${c.kind} "${c.value}" failed`),
    ]),
  '',
].join('\n');
writeFileSync(join(outDir, 'summary.md'), md);

console.log(md);
process.exit(asExpected === results.length ? 0 : 1);
